import { randomUUID } from 'node:crypto';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { TemporaryFile } from '@pod/core';

/**
 * A new file name in `directory`, named so the start-up sweep removes it if the
 * app stops before the caller disposes of it. `extension`, e.g. `.png`, is for
 * programs that choose the format by the name.
 */
export async function newTemporaryFile(directory: string, extension = ''): Promise<TemporaryFile> {
  await mkdir(directory, { recursive: true });
  const absolutePath = join(directory, `${randomUUID()}.download${extension}`);
  return { absolutePath, dispose: () => rm(absolutePath, { force: true }) };
}

/**
 * Writes generated bytes into the downloads folder and hands back a file the
 * caller disposes of once stored.
 */
export function temporaryFileWriter(directory: string) {
  return async (bytes: Uint8Array): Promise<TemporaryFile> => {
    const file = await newTemporaryFile(directory);
    await writeFile(file.absolutePath, bytes, { mode: 0o600 });
    return file;
  };
}
