export interface ServiceOptions {
  /** Folder that holds the database, stored assets and preferences. */
  readonly dataDirectory: string;
  /** Settings the seller has not changed read as these, besides the built-in defaults. */
  readonly defaultSettings: Pick<SettingsDto, 'language'>;
  readonly events: CatalogEvents & BatchEvents & UpscaleEvents;
  /** Protects connection secrets; Electron's `safeStorage` in the app. */
  readonly encryption: Encryption;
  readonly openExternal: (url: string) => Promise<void>;
  readonly logError: (error: unknown) => void;
  readonly fetch?: typeof fetch;
  /** Searches Etsy like a signed-out buyer; a hidden browser window in the app. */
  readonly marketSearch: MarketSearch;
  /** Renders a pin page as a PNG image; a hidden window in the app. */
  readonly renderPin: (html: string) => Promise<Uint8Array>;
  /** Scaled copies of stored images, shared with the window's thumbnails. */
  readonly thumbnails: ThumbnailCache;
  /** Turns thumbnails into the JPEG previews language models see; Electron's images in the app. */
  readonly bitmapCodec: BitmapCodec;
  /** Shows the system folder picker; `null` when cancelled. */
  readonly pickFolder: () => Promise<string | null>;
  /** Shows the system file picker for a keyword list; `null` when cancelled. */
  readonly pickKeywordFile: () => Promise<string | null>;
  /** Shows the system file picker for a PNG or JPEG photo; `null` when cancelled. */
  readonly pickImageFile: () => Promise<string | null>;
  /** Shows the system save dialog for a copy of a photo; `null` when cancelled. */
  readonly pickSavePath: (fileName: string) => Promise<string | null>;
  /** Folder holding the upscaling engine and its models; upscaling is off while it is missing. */
  readonly upscalerDirectory: string;
  /** Starts a worker thread that scales one PNG. */
  readonly startPngWorker: () => PngWorker;
}

/** What several services are built from, made once. */
export interface SharedParts {
  readonly options: ServiceOptions;
  readonly database: SqliteDatabase;
  readonly catalog: SqliteCatalog;
  readonly mockups: SqliteMockupRepository;
  readonly listings: SqliteListingRepository;
  /** Designs whose draft may be on Etsy, which no draft is made for until the seller checked. */
  readonly draftChecks: SqliteDraftChecks;
  readonly assets: ContentAddressedStore;
  readonly preferences: PreferencesFile;
  readonly secrets: ConnectionSecrets;
  /** Etsy and Pinterest sign-ins renewed but not saved, which the settings warn of. */
  readonly fetch: typeof fetch;
  readonly clock: Clock;
  readonly ids: IdGenerator;
  readonly inspector: ImageHeaderInspector;
  /** Small JPEG copies of stored images, for language models to look at. */
  readonly previews: ImagePreviews;
  /** Stores generated bytes where leftovers are swept at start-up. */
  readonly writeTemporary: (bytes: Uint8Array) => Promise<TemporaryFile>;
  readonly print: PrintProviders;
  /** One print check for the mockups and the listing draft. */
  readonly checkPrint: CheckDesignPrint;
}

/** Removes what an earlier run left half done: temporary files, unused assets and downloads. */
async function tidyDataFolder(
  dataDirectory: string,
  assets: ContentAddressedStore,
  database: SqliteDatabase,
): Promise<void> {
  await assets.removeTemporaryFiles();
  await new RemoveUnusedAssets(assets, new SqliteAssetReferences(database)).execute();
  await removeLeftoverDownloads(dataPath(dataDirectory, 'downloads'));
}

/**
 * Opens the stores and tidies them before any request is served, so no file
 * is half way between the asset store and its record.
 */
export async function prepareSharedParts(
  options: ServiceOptions,
  database: SqliteDatabase,
): Promise<SharedParts> {
  const assets = new ContentAddressedStore(dataPath(options.dataDirectory, 'assets'));
  await tidyDataFolder(options.dataDirectory, assets, database);

  const secrets = new ConnectionSecrets(
    new SecretFile(dataPath(options.dataDirectory, 'secrets'), options.encryption),
  );
  const fetchFn = options.fetch ?? globalThis.fetch;
  const clock: Clock = { now: () => new Date() };
  const ids: IdGenerator = { next: () => randomUUID() };
  const catalog = new SqliteCatalog(database);
  const print = createPrintProviders({
    secrets,
    dataDirectory: options.dataDirectory,
    fetch: fetchFn,
    clock,
    ids,
    onReleaseFailed: options.logError,
  });
  return {
    options,
    database,
    catalog,
    mockups: new SqliteMockupRepository(database),
    listings: new SqliteListingRepository(database),
    draftChecks: new SqliteDraftChecks(database),
    assets,
    preferences: new PreferencesFile(dataPath(options.dataDirectory, 'settings')),
    secrets,
    fetch: fetchFn,
    clock,
    ids,
    inspector: new ImageHeaderInspector(),
    previews: new ThumbnailPreviews(
      options.thumbnails,
      (key) => assets.pathOf(key),
      options.bitmapCodec,
    ),
    writeTemporary: temporaryFileWriter(dataPath(options.dataDirectory, 'downloads')),
    print,
    checkPrint: new CheckDesignPrint(catalog.query, print.printCatalog, print.generator),
  };
}
