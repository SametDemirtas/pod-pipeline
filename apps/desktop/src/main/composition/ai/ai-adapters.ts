import type { ModelCatalog, ModelChoice, TextModelCatalog } from '@pod/adapter-ai';
import {
  checkAnthropicKey,
  CLAUDE,
  CLAUDE_TEXT_MODELS,
  ClaudeModels,
} from '@pod/adapter-anthropic';
import {
  checkGeminiKey,
  GEMINI,
  GEMINI_SCENE_MODELS,
  GEMINI_TEXT_MODELS,
  GeminiModels,
  GeminiSceneGenerator,
} from '@pod/adapter-gemini';
import {
  checkOpenAiCompatibleKey,
  CompatibleModels,
  DEEPSEEK,
  KIMI,
  OPENAI,
  OPENAI_SCENE_MODELS,
  OpenAiSceneGenerator,
  type OpenAiVendor,
} from '@pod/adapter-openai';
import type { AiProvider, SceneProvider } from '@pod/contracts';
import type { SceneGenerator, TemporaryFile } from '@pod/core';

/** The seller's key and chosen model, read at the moment of asking. */
export interface ModelAccess {
  /** Resolves to `undefined` while no key is saved. */
  readonly apiKey: () => Promise<string | undefined>;
  readonly model: () => Promise<string>;
  readonly fetch: typeof fetch;
}

interface SceneAccess extends ModelAccess {
  /** Stores generated bytes in a temporary file the caller disposes of. */
  readonly writeTemporary: (bytes: Uint8Array, mimeType: string) => Promise<TemporaryFile>;
}

/** What the app needs from an AI service to write text and look at photos. */
interface TextAdapters {
  /** The name the seller knows the service by. */
  readonly service: string;
  readonly models: TextModelCatalog;
  /** Resolves when the service accepts the key, at no cost. */
  readonly checkKey: (apiKey: string, fetch: typeof globalThis.fetch) => Promise<void>;
  readonly choice: (access: ModelAccess) => ModelChoice;
}

/** What the app needs from an AI service to make scene photos. */
interface SceneAdapters {
  /** The name the seller knows the service by. */
  readonly service: AiService;
  readonly models: ModelCatalog;
  readonly generator: (access: SceneAccess) => SceneGenerator;
}

/** A service behind OpenAI's API, keeping its name's literal type for `AiService`. */
function compatible<V extends OpenAiVendor>(
  vendor: V,
): TextAdapters & { readonly service: V['service'] } {
  return {
    service: vendor.service,
    models: vendor,
    checkKey: (apiKey, fetch) => checkOpenAiCompatibleKey(vendor, apiKey, fetch),
    choice: (access) => new CompatibleModels(vendor, access),
  };
}

/** Every AI service the seller may choose to write text, by the key it is connected with. */
export const TEXT_ADAPTERS = {
  anthropic: {
    service: CLAUDE,
    models: CLAUDE_TEXT_MODELS,
    checkKey: checkAnthropicKey,
    choice: (access: ModelAccess) => new ClaudeModels(access),
  },
  openai: compatible(OPENAI),
  deepseek: compatible(DEEPSEEK),
  kimi: compatible(KIMI),
  gemini: {
    service: GEMINI,
    models: GEMINI_TEXT_MODELS,
    checkKey: checkGeminiKey,
    choice: (access: ModelAccess) => new GeminiModels(access),
  },
} as const satisfies Record<AiProvider, TextAdapters>;

/** The services that make scene photos, with the same keys as their text models. */
export const SCENE_ADAPTERS: Readonly<Record<SceneProvider, SceneAdapters>> = {
  gemini: {
    service: GEMINI,
    models: GEMINI_SCENE_MODELS,
    generator: (access) => new GeminiSceneGenerator(access),
  },
  openai: {
    service: OPENAI.service,
    models: OPENAI_SCENE_MODELS,
    generator: (access) => new OpenAiSceneGenerator(access),
  },
};

/** The name of an AI service as the seller knows it, e.g. `ChatGPT`. */
export type AiService = (typeof TEXT_ADAPTERS)[AiProvider]['service'];

/** The services chosen until the seller picks others. */
export const DEFAULT_TEXT_PROVIDER: AiProvider = 'anthropic';
export const DEFAULT_SCENE_PROVIDER: SceneProvider = 'gemini';
