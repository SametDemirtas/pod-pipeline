import { describe, expect, expectTypeOf, it } from 'vitest';
import {
  BATCH_JOB_STATES as CONTRACT_BATCH_JOB_STATES,
  BATCH_STEP_STATES as CONTRACT_BATCH_STEP_STATES,
  DRAFT_MAY_EXIST_CODES as CONTRACT_DRAFT_MAY_EXIST_CODES,
  DEFAULT_PAGE_SIZE as CONTRACT_DEFAULT_PAGE_SIZE,
  IMPORT_IMAGE_LIMITS,
  MAX_PAGE_SIZE as CONTRACT_MAX_PAGE_SIZE,
  LISTING_WRITER_LIMITS,
  MAX_KEYWORD_FILE_BYTES as CONTRACT_MAX_KEYWORD_FILE_BYTES,
  MAX_LIST_KEYWORDS as CONTRACT_MAX_LIST_KEYWORDS,
  MAX_RESEARCH_QUERY_LENGTH,
  MAX_SCENE_PROMPT_LENGTH as CONTRACT_MAX_SCENE_PROMPT_LENGTH,
  MAX_SEARCH_CHARACTERS as CONTRACT_MAX_SEARCH_CHARACTERS,
  RESEARCH_MARKETS,
  SCENE_LOOK_OPTIONS,
  SCENE_SHAPES as CONTRACT_SCENE_SHAPES,
  type AiTellCategoryDto,
} from '@pod/contracts';
import {
  BATCH_JOB_STATES,
  BATCH_STEP_STATES,
  DRAFT_MAY_EXIST_CODES,
  DEFAULT_PAGE_SIZE,
  LOOK_OPTIONS,
  MAX_KEYWORDS,
  MAX_NOTES_LENGTH,
  MARKET_REGIONS,
  MAX_IMAGE_PIXELS,
  MAX_KEYWORD_FILE_BYTES,
  MAX_LIST_KEYWORDS,
  MAX_IMAGE_SIDE,
  MAX_PAGE_SIZE,
  MAX_QUERY_LENGTH,
  MAX_SCENE_PROMPT_LENGTH,
  MAX_SEARCH_CHARACTERS,
  MAX_STYLE_LENGTH,
  SCENE_SHAPES,
  type AiTellCategory,
} from '@pod/core';

// The contracts cannot import the core, so the app, which sees both, checks they agree.
describe('limits', () => {
  it('are the same at the API boundary and in the core', () => {
    expect([
      CONTRACT_DEFAULT_PAGE_SIZE,
      CONTRACT_MAX_PAGE_SIZE,
      CONTRACT_MAX_SEARCH_CHARACTERS,
    ]).toEqual([DEFAULT_PAGE_SIZE, MAX_PAGE_SIZE, MAX_SEARCH_CHARACTERS]);
    expect(LISTING_WRITER_LIMITS).toEqual({ keywords: MAX_KEYWORDS, notes: MAX_NOTES_LENGTH });
    expect(MAX_RESEARCH_QUERY_LENGTH).toBe(MAX_QUERY_LENGTH);
    expect(CONTRACT_MAX_KEYWORD_FILE_BYTES).toBe(MAX_KEYWORD_FILE_BYTES);
    expect(CONTRACT_MAX_LIST_KEYWORDS).toBe(MAX_LIST_KEYWORDS);
    expect(RESEARCH_MARKETS).toEqual(MARKET_REGIONS);
    expect(CONTRACT_MAX_SCENE_PROMPT_LENGTH).toBe(MAX_SCENE_PROMPT_LENGTH);
    // A style description is put into the scene prompt, so it must fit there.
    expect(MAX_STYLE_LENGTH).toBeLessThanOrEqual(MAX_SCENE_PROMPT_LENGTH);
    expect(IMPORT_IMAGE_LIMITS).toEqual({ side: MAX_IMAGE_SIDE, pixels: MAX_IMAGE_PIXELS });
    expect(CONTRACT_SCENE_SHAPES).toEqual(SCENE_SHAPES);
    expect(SCENE_LOOK_OPTIONS).toEqual(LOOK_OPTIONS);
    expect(CONTRACT_BATCH_STEP_STATES).toEqual(BATCH_STEP_STATES);
    expect(CONTRACT_BATCH_JOB_STATES).toEqual(BATCH_JOB_STATES);
    expect(CONTRACT_DRAFT_MAY_EXIST_CODES).toEqual(DRAFT_MAY_EXIST_CODES);
    expectTypeOf<AiTellCategoryDto>().toEqualTypeOf<AiTellCategory>();
  });
});
