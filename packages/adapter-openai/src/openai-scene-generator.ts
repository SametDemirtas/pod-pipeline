import { readFile } from 'node:fs/promises';
import { basename } from 'node:path';
import OpenAI, { toFile } from 'openai';
import { AiAnswerError } from '@pod/adapter-ai';
import { mayHaveActed } from '@pod/adapter-http';
import type { SceneGenerator, SceneRequest, SceneShape, TemporaryFile } from '@pod/core';
import type { OpenAiAccess } from './compatible-models.js';
import {
  asVendor,
  OpenAiNotConnectedError,
  OpenAiSceneUnfinishedError,
  OpenAiVendorError,
} from './errors.js';
import { openAiClient } from './openai-client.js';
import { OPENAI } from './vendors.js';

/**
 * The size of each shape. Etsy wants 2000 pixels or more on the long side, and OpenAI calls
 * sizes above 2560x1440 pixels experimental, so the square stays at that many pixels.
 * Both sides are multiples of 16, as OpenAI requires.
 */
const SIZES: Readonly<Record<SceneShape, string>> = {
  '4:3': '2048x1536',
  '1:1': '1920x1920',
  '3:4': '1536x2048',
};

export interface OpenAiSceneOptions extends OpenAiAccess {
  /** Stores generated bytes in a temporary file the caller disposes of. */
  readonly writeTemporary: (bytes: Uint8Array, mimeType: string) => Promise<TemporaryFile>;
}

/** Builds scenes around the product photo with OpenAI's image edits. */
export class OpenAiSceneGenerator implements SceneGenerator {
  constructor(private readonly options: OpenAiSceneOptions) {}

  async generate(request: SceneRequest): Promise<TemporaryFile> {
    const apiKey = await this.options.apiKey();
    if (!apiKey) throw new OpenAiNotConnectedError(OPENAI);
    const { absolutePath, mimeType } = request.image;
    const photo = await readFile(absolutePath);
    const client = openAiClient(OPENAI, apiKey, {
      // A scene can take minutes, and one asked for again may be billed twice.
      timeout: 300_000,
      maxRetries: 0,
      fetch: this.options.fetch,
    });
    const image = await toFile(photo, basename(absolutePath), { type: mimeType });
    const model = await this.options.model();
    const response = await asVendor(OPENAI, () =>
      client.images.edit({
        model,
        image,
        prompt: request.prompt,
        quality: 'high',
        // A JPEG keeps a listing photo a few megabytes, where PNG would be many more.
        output_format: 'jpeg',
        size: SIZES[request.shape],
      }),
    ).catch((error: unknown) => {
      throw sceneFailure(error);
    });
    const scene = response.data?.[0]?.b64_json;
    if (!scene) throw new AiAnswerError(OPENAI.service, `${OPENAI.service} returned no image`);
    return this.options.writeTemporary(Buffer.from(scene, 'base64'), 'image/jpeg');
  }
}

/** A fault on the service's side may come after the scene was made, so its outcome is unknown. */
function sceneFailure(error: unknown): unknown {
  return error instanceof OpenAiVendorError && mayHaveActed(error.cause, OpenAI.APIError)
    ? new OpenAiSceneUnfinishedError(error.service, error)
    : error;
}
